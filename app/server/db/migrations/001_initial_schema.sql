CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) NOT NULL,
  email VARCHAR(320) NOT NULL,
  email_normalized VARCHAR(320) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  role ENUM('user', 'admin') NOT NULL DEFAULT 'user',
  status ENUM('pending_verification', 'active', 'suspended', 'deleted') NOT NULL DEFAULT 'pending_verification',
  plan_id CHAR(36) NOT NULL DEFAULT '00000000-0000-4000-8000-000000000001',
  email_verified_at DATETIME(3) NULL,
  trial_started_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  trial_used_at DATETIME(3) NULL,
  last_login_at DATETIME(3) NULL,
  password_changed_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
