-- CineAssemble production schema for MySQL 8.0+
-- All customer-owned records carry user_id and are accessed through tenant-scoped repositories.

CREATE TABLE IF NOT EXISTS plans (
  id CHAR(36) NOT NULL,
  code VARCHAR(32) NOT NULL,
  name VARCHAR(80) NOT NULL,
  price_monthly_cents INT UNSIGNED NOT NULL DEFAULT 0,
  monthly_credits INT UNSIGNED NOT NULL DEFAULT 0,
  max_video_minutes TINYINT UNSIGNED NOT NULL DEFAULT 5,
  max_concurrent_jobs TINYINT UNSIGNED NOT NULL DEFAULT 1,
  watermark_required BOOLEAN NOT NULL DEFAULT TRUE,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  entitlements JSON NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_plans_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

